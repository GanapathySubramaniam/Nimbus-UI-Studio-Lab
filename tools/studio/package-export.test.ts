  // Independent ZIP reader checks central directory offsets and CRC values using node:zlib.
  function unzip(bytes: Uint8Array) {
    const buffer = Buffer.from(bytes);
    const end = buffer.length - 22;
    assert.equal(buffer.readUInt32LE(end), 0x06054b50);
    const files = new Map<string, Buffer>();
    let offset = buffer.readUInt32LE(end + 16);
    for (let i = 0; i < buffer.readUInt16LE(end + 10); i++) {
      assert.equal(buffer.readUInt32LE(offset), 0x02014b50);
      assert.equal(buffer.readUInt16LE(offset + 10), 0);
      const length = buffer.readUInt16LE(offset + 28);
      const name = buffer.subarray(offset + 46, offset + 46 + length).toString();
      const local = buffer.readUInt32LE(offset + 42);
      assert.equal(buffer.readUInt32LE(local), 0x04034b50);
      const start = local + 30 + buffer.readUInt16LE(local + 26) + buffer.readUInt16LE(local + 28);
      const data = buffer.subarray(start, start + buffer.readUInt32LE(offset + 24));
      assert.equal(buffer.readUInt32LE(local + 14), buffer.readUInt32LE(offset + 16));
      assert.equal(buffer.readUInt32LE(offset + 16), referenceCrc32(data));
      assert.equal(buffer.readUInt16LE(local + 6), 0x800);
      files.set(name, data);
      offset += 46 + length + buffer.readUInt16LE(offset + 30) + buffer.readUInt16LE(offset + 32);
    }
    return files;
  }

  test("stored ZIP preserves Unicode names, binary bytes, CRC and central offsets", async () => {
    const { crc32 } = await import("node:zlib");
    assert.equal(zip.crc32(new TextEncoder().encode("123456789")), 0xcbf43926);
    const entries = [{ name: "assets/你好.png", data: new Uint8Array([0, 128, 255, 13, 10]) },
      { name: "empty.txt", data: "" }, { name: "README.md", data: "Hello π" }];
    const bytes = zip.createZip(entries);
    const result = unzip(bytes);
    for (const entry of entries) {
      const expected = typeof entry.data === "string" ? Buffer.from(entry.data) : Buffer.from(entry.data);
      assert.deepEqual(result.get(entry.name), expected);
      assert.equal(zip.crc32(expected), crc32(expected));
    }
    assert.equal(unzip(zip.createZip([])).size, 0);
  });

