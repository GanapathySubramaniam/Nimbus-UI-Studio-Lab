  let compiledRuntime: Promise<string> | undefined;
  async function runPackagedRuntime(input: ReturnType<typeof project>, href: string) {
    const archive = pkg.createReactPackage(input);
    const appRequire = createRequire(join(root, "apps/reference-vite/package.json"));
    compiledRuntime ??= (async () => {
      const sources = new Map(archive.entries.filter((entry) => entry.name.startsWith("packages/runtime/src/"))
        .map((entry) => ["\0nimbus/" + entry.name.slice("packages/runtime/src/".length), String(entry.data)]));
      const { build } = await import(pathToFileURL(appRequire.resolve("vite")).href);
      const result = await build({
        configFile: false, root, logLevel: "silent",
        plugins: [{ name: "extracted-nimbus-runtime",
          resolveId(id: string, importer?: string) {
            if (id.endsWith("virtual:nimbus-runtime")) return "\0nimbus/index.tsx";
            if (!id.startsWith(".") || !importer?.startsWith("\0nimbus/")) return undefined;
            const path = posix.normalize(posix.join(posix.dirname(importer), id));
            return [path, path + ".ts", path + ".tsx"].find((name) => sources.has(name));
          },
          load(id: string) { return sources.get(id); },
        }],
        build: { write: false, minify: false, lib: { entry: "virtual:nimbus-runtime", formats: ["cjs"] },
          rolldownOptions: { external: ["react", "react/jsx-runtime"] } },
      });
      const bundle = Array.isArray(result) ? result[0] : result;
      return bundle.output.find((item: { type: string }) => item.type === "chunk")!.code;
    })();
    let html = "";
    // Only React's hook scheduling is replaced in this non-DOM harness. The emitted
    // component, asset adapter, shared renderer and fixed script all execute unchanged.
    const react = appRequire("react");
    const require = (name: string) => name === "react" ? { ...react,
      useEffect: (effect: () => void) => effect(),
      useState: () => ["", (value: string) => { html = value; }],
    } : appRequire(name);
    const module = { exports: {} as { NimbusPrototype?: (props: unknown) => unknown } };
    runInNewContext(await compiledRuntime, { require, module, exports: module.exports, URL,
      window: { location: { href } } });
    module.exports.NimbusPrototype!({ project: archive.project });
    assert.ok(html, "The runtime effect must publish an iframe document");
    return html;
  }

